"""Statewide county and municipal finances, FY 2023-24 -> inputs/fl_local_finance_fy2024.yaml

Usage:
    python scripts/fl_local_finance_2024.py

Reads EDR's account-total files (Annual Financial Reports, local fiscal year ended Sept 30, 2024)
from data/raw/fl_edr_localgov/ (download from
https://edr.state.fl.us/Content/local-government/data/revenues-expenditures/stwidefiscal.cfm):
  cntyfiscal/2024revenuetotalsbycounty.xlsx, cntyfiscal/2024expendituretotalsbycounty.xlsx,
  munifiscal/2024revenuetotalsbymunicipality.xlsx, munifiscal/2024expendituretotalsbymunicipality.xlsx
Uses the statewide "adjusted" totals, which exclude amounts reported in the Custodial Fund (taxes a
county collects for other governments). County totals exclude Duval/Jacksonville (EDR reports it
separately). Per-government figures are not used: unadjusted county files mix in custodial amounts.
For the page's "for scale" line only.
"""

from pathlib import Path

import numpy as np
import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw" / "fl_edr_localgov"
DEST = ROOT / "inputs" / "fl_local_finance_fy2024.yaml"


def summary(name: str) -> tuple[dict, pd.DataFrame]:
    d = pd.read_excel(RAW / f"{name}.xlsx", sheet_name=0, header=None)
    cats = d[d[1].isna() & d[0].notna() & pd.to_numeric(d[6], errors="coerce").notna()]
    adj = {str(r[0]).strip(): float(r[6]) for _, r in cats.iterrows()}
    return adj, d


def account(d: pd.DataFrame, code: float) -> float:
    c = pd.to_numeric(d[1], errors="coerce")
    return float(d[np.isclose(c, code)].iloc[0, 6])


def main() -> None:
    out = {}
    for who, rev, exp in [("counties", "2024revenuetotalsbycounty", "2024expendituretotalsbycounty"),
                          ("cities", "2024revenuetotalsbymunicipality", "2024expendituretotalsbymunicipality")]:
        r, rd = summary(rev)
        e, _ = summary(exp)
        total = r["Total - All Account Codes"]
        out[who] = {"ad_valorem_taxes": round(account(rd, 311.0)),
                    "revenue_excluding_other_sources": round(total - r["Other Sources"]),
                    "public_safety_spending": round(e["Public Safety"])}
    both = {k: out["counties"][k] + out["cities"][k] for k in out["counties"]}
    out["counties_and_cities"] = both
    out["property_tax_share_of_revenue"] = round(both["ad_valorem_taxes"] / both["revenue_excluding_other_sources"], 4)
    out["property_tax_per_public_safety_dollar"] = round(both["ad_valorem_taxes"] / both["public_safety_spending"], 4)
    out["source"] = ("EDR, county and municipal revenue and expenditure account totals, local fiscal year ended "
                     "Sept 30, 2024; statewide adjusted totals (exclude Custodial Fund amounts); counties exclude "
                     "Duval/Jacksonville. Revenue excludes Other Sources (interfund transfers, debt proceeds).")
    out["source_url"] = "https://edr.state.fl.us/Content/local-government/data/revenues-expenditures/stwidefiscal.cfm"
    DEST.write_text("# Generated by scripts/fl_local_finance_2024.py\n" + yaml.safe_dump(out, sort_keys=False), encoding="utf-8")
    print(DEST.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
